CREATE TABLE "products" (
  "id" UUID NOT NULL DEFAULT uuidv7(),
  "tenant_id" UUID NOT NULL,
  "organization_unit_id" UUID,
  "sku" VARCHAR(64) NOT NULL,
  "normalized_sku" VARCHAR(64) NOT NULL,
  "name" VARCHAR(150) NOT NULL,
  "description" TEXT,
  "category" VARCHAR(120),
  "unit" VARCHAR(32) NOT NULL,
  "price" NUMERIC(19,4) NOT NULL,
  "currency" VARCHAR(3) NOT NULL,
  "tax_code" VARCHAR(64),
  "tax_rate" NUMERIC(9,4),
  "active" BOOLEAN NOT NULL DEFAULT TRUE,
  "is_exceptional" BOOLEAN NOT NULL DEFAULT FALSE,
  "custom_values" JSONB,
  "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(3) NOT NULL,
  CONSTRAINT "products_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "products_tenant_id_id_key" UNIQUE ("tenant_id", "id"),
  CONSTRAINT "products_tenant_normalized_sku_key" UNIQUE ("tenant_id", "normalized_sku"),
  CONSTRAINT "products_price_check" CHECK ("price" >= 0 AND "price" <= 999999999.9999),
  CONSTRAINT "products_tax_rate_check" CHECK ("tax_rate" IS NULL OR ("tax_rate" >= 0 AND "tax_rate" <= 100)),
  CONSTRAINT "products_sku_check" CHECK (char_length("sku") BETWEEN 1 AND 64 AND "sku" = btrim("sku") AND "sku" !~ '[[:cntrl:]]'),
  CONSTRAINT "products_normalized_sku_check" CHECK (char_length("normalized_sku") BETWEEN 1 AND 64 AND "normalized_sku" = upper(btrim("normalized_sku")) AND "normalized_sku" !~ '[[:cntrl:]]'),
  CONSTRAINT "products_name_check" CHECK (char_length("name") BETWEEN 1 AND 150 AND "name" = btrim("name")),
  CONSTRAINT "products_description_check" CHECK ("description" IS NULL OR char_length("description") <= 2000),
  CONSTRAINT "products_category_check" CHECK ("category" IS NULL OR char_length("category") <= 120),
  CONSTRAINT "products_unit_check" CHECK (char_length("unit") BETWEEN 1 AND 32 AND "unit" = btrim("unit")),
  CONSTRAINT "products_tax_code_check" CHECK ("tax_code" IS NULL OR char_length("tax_code") <= 64),
  CONSTRAINT "products_currency_check" CHECK ("currency" ~ '^[A-Z]{3}$'),
  CONSTRAINT "products_custom_values_check" CHECK ("custom_values" IS NULL OR (jsonb_typeof("custom_values") = 'object' AND octet_length("custom_values"::text) <= 16384)),
  CONSTRAINT "products_tenant_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenant"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "products_organization_unit_fkey" FOREIGN KEY ("tenant_id", "organization_unit_id") REFERENCES "organization_unit"("tenant_id", "id") ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE INDEX "products_tenant_active_id_idx" ON "products"("tenant_id", "active", "id");
CREATE INDEX "products_tenant_unit_id_idx" ON "products"("tenant_id", "organization_unit_id", "id");
